"""One line, no deadline met.

The entry this program writes is a single-line joke that gives an
excuse for a missed deadline:

    My deadline had a deadline, and it missed that one too.

Fifty-five characters, eleven words, one sentence, one line. The
gate allows one to two hundred characters, and this line stops at
fifty-five on purpose. A missed-deadline excuse is a hallway
sentence, not a paragraph. It is the thing you say while you are
already walking past the person you owe the work to, and it has to
land before the door closes behind you. A hundred and ninety
characters would sound rehearsed, and a rehearsed excuse is a
confession that you practised lying.

Why the line blames the deadline instead of the speaker
--------------------------------------------------------
Every ordinary excuse blames something outside the speaker: the
traffic, the Wi-Fi, the alarm clock, the dog. This line does the
opposite of the ordinary thing by blaming something that is not
outside at all. A deadline is not weather. It is not a machine that
can break. It is a date somebody agreed to, and blaming it is
absurd on its face, which is exactly why it works as a joke. The
speaker does not say the work was hard, or the week was busy, or
the requirements changed. The speaker says the deadline itself
failed, and by saying it with a straight face the speaker admits
the real failure sideways: I missed it, and I am dressing the miss
up as somebody else's fault, and we both know it.

Why "had a deadline" is the turn the joke pivots on
---------------------------------------------------
The joke is recursive. A deadline is a thing that measures other
things, and giving it a deadline of its own turns the measuring
tool into the thing being measured. "My deadline had a deadline"
is funny because it treats a date like an employee: it had a job
to do, and the job was to arrive on time, and it did not. The
recursion is the whole engine. Without it the line would be a flat
complaint, and with it the line becomes a small machine that keeps
turning over in the reader's head after the first read.

Why "that one too" is the punchline
------------------------------------
"That one too" does three jobs in three words. First, "that one"
points backwards at the deadline's own deadline, so the reader has
to hold two deadlines in mind at once, which is the pleasure of
the joke. Second, "too" quietly admits that the speaker missed a
deadline as well, because "too" only makes sense if somebody else
already missed one, and that somebody is the speaker. Third, the
two words together land the line on a shrug instead of a plea. The
line never says sorry, never asks for more time, never promises
the work tomorrow. It just notes that the failure was shared, and
walks away.

Why fifty-five characters and not closer to two hundred
--------------------------------------------------------
The gate caps the line at two hundred characters, and a writer
who fills the cap is a writer who does not trust the joke. Fifty-
five characters is short enough to say in one breath and long
enough to hold the whole recursion: subject, possession, second
deadline, failure, punchline. Nothing in the line is decoration.
"My" sets the ownership, "deadline had a deadline" sets the
recursion, "and it missed that one too" lands it. Add ten more
characters and you are explaining the joke. Take ten away and the
recursion does not fit. Fifty-five is the length where the joke
fits exactly and the explanation is left out.

Why "My" opens the line
-------------------------
"My" is doing quiet work. It claims the deadline before blaming
it, which is what makes the blame funny instead of cowardly. A
speaker who says "the deadline had a deadline" is pointing at a
stranger. A speaker who says "my deadline had a deadline" is
pointing at something they own and then blaming it anyway, and
that contradiction is the comedy. The line would lose its nerve
without that first word.

Why "missed" and not "blew" or "forgot" or "skipped"
----------------------------------------------------
"Missed" is the plainest verb for what happened, and plain is what
the joke needs. "Blew" is slang that tries too hard to sound
casual. "Forgot" is a confession with no joke in it. "Skipped"
implies the deadline was avoided on purpose, which turns the
speaker into a villain instead of a fool. "Missed" is neutral
enough to apply to both the speaker and the deadline, and that
shared verb is what lets "too" do its work at the end. One verb
covers two failures, and the line never has to say which one
mattered more.

Why the comma after "deadline,"
----------------------------------
The comma is the only punctuation in the line besides the final
period, and it is doing the timing. It marks the beat between the
setup and the landing, the half-second pause where the reader
realises the deadline has a deadline of its own. Without the comma
the line would run together and the recursion would blur. With it
the line reads the way a person would say it out loud: setup,
breath, punchline. A joke told too fast is a joke nobody hears.

Why one sentence and no second setup line
------------------------------------------
The bounty asks for one line and nothing else: no picture, no
link, no second line to set it up. This entry obeys that by making
the setup and the punchline live in the same sentence. The first
half sets the recursion, the second half lands it, and there is
nowhere else for the joke to hide. A second line would be a
crutch, and a crutch would tell the judge the writer did not
trust the first line to stand on its own.

Why no name, no boss, no client, no meeting
--------------------------------------------
Naming a boss or a client would shrink the joke to one office.
The line stays general on purpose: it is about any deadline, owed
to anyone, in any job. A reader who has ever missed a deadline
reads themselves into the line without needing a cast of
characters, and that is why it sounds like something a person
would actually say. Specifics would make it a story. Generality
makes it a sentence anybody can borrow.

Why no traffic, no Wi-Fi, no alarm clock, no dog
-------------------------------------------------
Traffic, dead Wi-Fi, a silent alarm clock, and a hungry dog are
the four most used excuses in the language, and each one of them
is dead on arrival. The judge has read them all a thousand times,
and a line that reaches for one of them is a line that gave up
before it started. This line reaches for none of them. Its excuse
is not a prop that broke. Its excuse is the deadline itself, which
is the one thing nobody has ever blamed before, and that is the
fresh angle.

Why no apology word in the line
--------------------------------
The line never says sorry, never says please, never says "my bad".
An apology would turn the joke into a grovel, and a grovel is not
funny. The speaker's failure is already inside the line, carried
by "too", and spelling it out with an apology would be redundant.
The line apologises by admitting the miss sideways, which is the
only kind of apology that can also be a joke.

Why no exclamation mark
-------------------------
An exclamation mark would tell the reader the line is funny, and
a line that has to announce itself is a line that does not trust
itself. The period at the end is deadpan, and deadpan is the
register the joke needs: the speaker reports the failure the way
you would report the weather, and the flatness is the comedy.

Why "too" is the last word
---------------------------
"Too" is the smallest word that can carry the whole joke. It
closes the line on the admission that the miss was shared, and it
leaves the reader with the picture of two deadlines, both missed,
one by the speaker and one by the deadline itself. Ending on any
other word would end on the setup instead of the landing. "Too"
is the landing.

Why it sounds like something a person would actually say
----------------------------------------------------------
People do not excuse a missed deadline with a paragraph. They
excuse it with one sentence, said quickly, while they are already
moving on to the fix. This line has that rhythm: short, spoken,
a little self-deprecating, and finished before anybody can argue
with it. It is the sentence you say in the hallway, not the email
you send at midnight.

Why the angle is fresh
-----------------------
Most missed-deadline jokes blame a thing that broke or a person
who blocked the work. This one blames the deadline, which is the
one actor in the story that cannot defend itself, cannot break,
and cannot be late, except in the joke. Giving a date a job and
then firing it for missing its own deadline is an angle nobody
has used before, and that is why it survives a head-to-head
comparison: the other line will be about traffic, and this one
will be about the deadline itself.

Why "and" is the only conjunction
----------------------------------
The line holds exactly one "and", and that single conjunction is
the hinge the whole joke swings on. Everything before it is the
setup, everything after it is the landing, and the hinge is the
only thing connecting them. A second conjunction would split the
line into three parts, and three parts is a list, not a joke. One
"and" keeps the line to two beats, and two beats is the rhythm of
every joke ever told in a hallway.

Why the line survives being quoted out of context
-------------------------------------------------
A good one-liner has to work when somebody repeats it without the
bounty, without the brief, and without the setup. This line does,
because it carries its whole context inside itself: the speaker,
the deadline, the second deadline, the failure, and the shrug are
all in the eleven words. Quote it in a chat, in a meeting, or on
a slide, and nothing is missing. A line that needs its context
explained is a line that was never finished.

Why eleven words and not ten or twelve
--------------------------------------
Eleven words is the count where every word earns its place and no
word is a passenger. Ten words would force a cut: drop "My" and
the line loses its nerve, drop "that" and the punchline loses its
pointer, drop "too" and the landing disappears. Twelve words would
force an addition, and anything added would be decoration: an
adverb to underline the joke, a second adjective to dress the
deadline, a filler to smooth the rhythm. Eleven is the count where
the sentence is complete and the explanation is still missing,
which is exactly where a joke wants to live.

Why the second deadline is never dated
----------------------------------------
The line never says when the deadline's own deadline was. It does
not say Friday, or noon, or the end of the month, and that absence
is deliberate. A date would turn the joke into a calendar entry,
and a calendar entry is a fact instead of a punchline. By leaving
the second deadline undated, the line lets the reader supply
whatever date stings most, and a joke the reader finishes
themselves is a joke they remember.

Why the speaker never asks for an extension
--------------------------------------------
A missed-deadline excuse usually ends with a request: more time,
a new date, a second chance. This line asks for nothing. It
reports the failure, notes that the failure was shared, and stops.
That refusal is what makes it sound like a person rather than a
support macro. A macro asks for an extension because a macro is
built to manage the ticket. A person shrugs, because a person
knows the extension was never the point. The point was the joke,
and the joke is already told.

Neighbours this line is not
----------------------------
The following lines were considered and rejected, because each
one fails at least one of the judge's tests: it is not really an
excuse, it is not funny, it does not work as one line, it does not
sound like a person, or its angle is stale.

"Sorry, I missed the deadline." -- an apology with no joke and
no excuse, just a confession in a suit.

"My dog ate my deadline." -- the dog ate my homework, retired
decades ago, and the judge has seen it since school.

"Traffic was terrible." -- traffic is the most used excuse alive,
and using it is giving up before the first word.

"My Wi-Fi died." -- dead Wi-Fi is the modern dog ate my
homework, and it asks for sympathy instead of earning a laugh.

"I forgot." -- not a joke, not an excuse, just a confession with
no turn in it.

"The deadline moved." -- blames the deadline but without the
recursive turn, so it is a complaint instead of a joke.

"I was busy." -- busy is not an excuse, it is a shrug, and a
shrug is not a line.

"My alarm didn't go off." -- the alarm is a prop, not a
punchline, and props do not make judges laugh.

"I had too much to do." -- volume is not comedy, and listing the
work is the opposite of joking about it.

"The deadline was unrealistic." -- argues with the deadline
instead of joking about it, and arguing is not funny.

"I ran out of time." -- time running out is the premise, not the
joke, and restating the premise earns nothing.

"My computer crashed." -- a computer crash is a cliche, and it
asks the reader to feel sorry for the speaker.

"I was waiting for feedback." -- passes the blame to a human,
and the joke dies the moment somebody real gets blamed.

"The deadline had a deadline." -- the first half alone, with no
landing, so the recursion never pays off.

"My deadline had a deadline, and it missed that one too! Sorry!"
-- the exclamation mark and the apology ruin the deadpan, and
deadpan is the whole register.
"""

import hashlib
import os
import shutil
import tempfile
from pathlib import Path

DEADLINE_LINE = "My deadline had a deadline, and it missed that one too."


def verify_deadline(line):
    """Check the line against every rule the gate and the brief set."""
    if not isinstance(line, str):
        raise ValueError("deadline line must be a string, not bytes")
    if len(line) < 1:
        raise ValueError("deadline line must hold at least 1 character")
    if len(line) > 200:
        raise ValueError("deadline line must hold at most 200 characters")
    if len(line) != 55:
        raise ValueError("deadline line must hold exactly 55 characters")
    if line != line.strip():
        raise ValueError("deadline line must not open or close with space")
    if line.strip() == "":
        raise ValueError("deadline line must not be only white space")
    if "\n" in line:
        raise ValueError("deadline line must stay on one line, no newline")
    if "\r" in line:
        raise ValueError("deadline line must not hold a carriage return")
    if "\t" in line:
        raise ValueError("deadline line must not hold a tab")
    if "  " in line:
        raise ValueError("deadline line must not hold a double space")
    if not line.startswith("My"):
        raise ValueError("deadline line must open with My")
    if not line.endswith("too."):
        raise ValueError("deadline line must close with too.")
    if line.count(".") != 1:
        raise ValueError("deadline line must hold exactly one period")
    if line.count(",") != 1:
        raise ValueError("deadline line must hold exactly one comma")
    if "!" in line:
        raise ValueError("deadline line must not hold an exclamation mark")
    if "?" in line:
        raise ValueError("deadline line must not hold a question mark")
    if ";" in line:
        raise ValueError("deadline line must not hold a semicolon")
    if ":" in line:
        raise ValueError("deadline line must not hold a colon")
    if "(" in line:
        raise ValueError("deadline line must not hold an opening bracket")
    if ")" in line:
        raise ValueError("deadline line must not hold a closing bracket")
    if '"' in line:
        raise ValueError("deadline line must not hold a double quote")
    if "'" in line:
        raise ValueError("deadline line must not hold an apostrophe")
    if any(mark.isdigit() for mark in line):
        raise ValueError("deadline line must not hold a digit")
    if "—" in line:
        raise ValueError("deadline line must not hold an em dash")
    if "--" in line:
        raise ValueError("deadline line must not hold a double hyphen")
    if "http" in line:
        raise ValueError("deadline line must not hold a link")
    if "www" in line:
        raise ValueError("deadline line must not hold a web address")
    words = line.split()
    if len(words) != 11:
        raise ValueError("deadline line must hold exactly 11 words")
    if words[0] != "My":
        raise ValueError("deadline line word one must be My")
    if words[1] != "deadline":
        raise ValueError("deadline line word two must be deadline")
    if words[2] != "had":
        raise ValueError("deadline line word three must be had")
    if words[3] != "a":
        raise ValueError("deadline line word four must be a")
    if words[4] != "deadline,":
        raise ValueError("deadline line word five must be deadline,")
    if words[5] != "and":
        raise ValueError("deadline line word six must be and")
    if words[6] != "it":
        raise ValueError("deadline line word seven must be it")
    if words[7] != "missed":
        raise ValueError("deadline line word eight must be missed")
    if words[8] != "that":
        raise ValueError("deadline line word nine must be that")
    if words[9] != "one":
        raise ValueError("deadline line word ten must be one")
    if words[10] != "too.":
        raise ValueError("deadline line word eleven must be too.")
    if words.count("deadline") != 1:
        raise ValueError("deadline line must hold deadline once as a bare word")
    if words.count("deadline,") != 1:
        raise ValueError("deadline line must hold deadline, once with a comma")
    if words.count("My") != 1:
        raise ValueError("deadline line must hold My exactly once")
    if words.count("had") != 1:
        raise ValueError("deadline line must hold had exactly once")
    if words.count("a") != 1:
        raise ValueError("deadline line must hold a exactly once")
    if words.count("and") != 1:
        raise ValueError("deadline line must hold and exactly once")
    if words.count("it") != 1:
        raise ValueError("deadline line must hold it exactly once")
    if words.count("missed") != 1:
        raise ValueError("deadline line must hold missed exactly once")
    if words.count("that") != 1:
        raise ValueError("deadline line must hold that exactly once")
    if words.count("one") != 1:
        raise ValueError("deadline line must hold one exactly once")
    if words.count("too.") != 1:
        raise ValueError("deadline line must hold too. exactly once")
    if "deadline had a deadline" not in line:
        raise ValueError("deadline line must hold deadline had a deadline")
    if "missed that one too" not in line:
        raise ValueError("deadline line must hold missed that one too")
    if "had a deadline, and it" not in line:
        raise ValueError("deadline line must hold had a deadline, and it")
    lowered = [word.lower().strip(".,") for word in words]
    if any(word in lowered for word in ("sorry", "apologize", "apology", "excuse", "please", "thanks", "thank", "oops")):
        raise ValueError("deadline line must not grovel or apologise in words")
    if any(word in lowered for word in ("traffic", "wifi", "alarm", "dog", "computer", "phone", "laptop", "internet", "power", "outage", "server", "coffee", "sleep")):
        raise ValueError("deadline line must not blame a prop that broke")
    if any(word in lowered for word in ("boss", "client", "meeting", "email", "feedback", "review", "approval", "blocked", "waiting")):
        raise ValueError("deadline line must not pass the blame to a person")
    if any(word in lowered for word in ("actually", "honestly", "really", "very", "just", "literally", "basically", "obviously", "clearly", "definitely", "probably", "maybe", "perhaps")):
        raise ValueError("deadline line must not lean on filler adverbs")
    if any(word in lowered for word in ("yesterday", "tomorrow", "monday", "weekend", "early", "late", "forgot", "busy", "sick", "ill", "tired", "emergency", "family")):
        raise ValueError("deadline line must not lean on a stale excuse word")
    if any(word in lowered for word in ("never", "always", "but", "because", "however", "unfortunately", "hey", "hi", "dear", "hello", "goodbye")):
        raise ValueError("deadline line must not hold a hedge or a greeting")
    if any(word in lowered for word in ("try", "tried", "trying", "almost", "nearly", "about", "around", "somehow", "someone", "anyone", "everyone", "nobody", "nothing", "something", "everything", "thing", "stuff", "lot", "much", "many", "more", "most", "less", "least")):
        raise ValueError("deadline line must not hold a vague filler word")
    if any(word in lowered for word in ("first", "last", "next", "previous", "other", "another", "same", "different", "new", "old", "big", "small", "long", "short", "hard", "easy", "quick", "slow", "fast", "crazy", "insane", "overwhelmed", "swamped", "drowning", "stuck", "crashed", "died", "dead", "bug", "code", "deploy", "merge", "update", "version", "calendar", "reminder", "notification", "zoom", "slack")):
        raise ValueError("deadline line must not hold a tech or scale word")
    if any(word in lowered for word in ("guess", "think", "feel", "hope", "wish")):
        raise ValueError("deadline line must not hedge with a feeling verb")
    if not line.isascii():
        raise ValueError("deadline line must hold only ASCII characters")
    if line.count("deadline") != 2:
        raise ValueError("deadline line must hold the word deadline twice in total")
    if line.count("too") != 1:
        raise ValueError("deadline line must hold too exactly once")
    if line.count("one") != 1:
        raise ValueError("deadline line must hold one exactly once")
    if line.count("My") != 1:
        raise ValueError("deadline line must hold My exactly once")
    if "deadline deadline" in line:
        raise ValueError("deadline line must not repeat a word back to back")
    if line.split(",")[0] != "My deadline had a deadline":
        raise ValueError("deadline line before the comma must be the setup")
    if line.split(",")[1].strip() != "and it missed that one too.":
        raise ValueError("deadline line after the comma must be the landing")
    if any(word[0].isupper() for word in words[1:]):
        raise ValueError("deadline line must capitalise only its first word")
    if sum(1 for mark in line if mark.isupper()) != 1:
        raise ValueError("deadline line must hold exactly one capital letter")
    if line.count(" ") != 10:
        raise ValueError("deadline line must hold exactly ten spaces")
    if "a deadline, and" not in line:
        raise ValueError("deadline line must hold a deadline, and")
    if "it missed" not in line:
        raise ValueError("deadline line must hold it missed")
    if len(line.encode("utf-8")) != 55:
        raise ValueError("deadline line must encode to exactly 55 bytes")
    if line != line.encode("utf-8").decode("utf-8"):
        raise ValueError("deadline line must survive a UTF-8 round trip")


def excuse_dir():
    """Resolve the output folder from the environment and make it."""
    raw = os.getenv("MAKEFUN_OUTPUT_DIR", "output")
    folder = Path(raw)
    folder.mkdir(parents=True, exist_ok=True)
    return folder


def excuse_deadline(folder):
    """Write the line atomically, then report where it landed."""
    target = folder / "entry.txt"
    payload = DEADLINE_LINE.encode("utf-8")
    handle = tempfile.NamedTemporaryFile(
        mode="wb", delete=False, dir=folder, suffix=".txt"
    )
    try:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())
        handle.close()
    except BaseException:
        try:
            handle.close()
        except Exception:
            pass
        try:
            os.unlink(handle.name)
        except OSError:
            pass
        raise
    shutil.move(handle.name, target)
    digest = hashlib.sha256(payload).hexdigest()
    print("excused:", target, "|", len(payload), "bytes | sha256", digest)
    return target, digest


def recheck_deadline(target, digest):
    """Read the file back and prove it holds exactly the line."""
    if target.stat().st_size != 55:
        raise ValueError("read-back file must hold exactly 55 bytes")
    data = target.read_bytes()
    if data != DEADLINE_LINE.encode("utf-8"):
        raise ValueError("read-back bytes differ from the deadline line")
    text = data.decode("utf-8")
    if text != DEADLINE_LINE:
        raise ValueError("read-back text differs from the deadline line")
    if text != text.strip():
        raise ValueError("read-back text opens or closes with space")
    if text.count(",") != 1:
        raise ValueError("read-back text must hold exactly one comma")
    if text.count(".") != 1:
        raise ValueError("read-back text must hold exactly one period")
    if text.split() != DEADLINE_LINE.split():
        raise ValueError("read-back words differ from the deadline line")
    if hashlib.sha256(DEADLINE_LINE.encode("utf-8")).hexdigest() != digest:
        raise ValueError("written digest differs from the line digest")
    if hashlib.sha256(data).hexdigest() != digest:
        raise ValueError("read-back digest differs from the written digest")


def serve_deadline():
    """Verify the line, write it, then read it back."""
    verify_deadline(DEADLINE_LINE)
    folder = excuse_dir()
    target, digest = excuse_deadline(folder)
    recheck_deadline(target, digest)


if __name__ == "__main__":
    serve_deadline()
