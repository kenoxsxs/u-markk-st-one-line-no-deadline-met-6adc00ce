def missed_dir():
    """Resolve the output folder and make sure it exists."""
    raw = os.environ.get("MAKEFUN_OUTPUT_DIR", "")
    if raw.strip():
        folder = pathlib.Path(raw)
    else:
        folder = pathlib.Path.cwd() / "output"
    folder.mkdir(parents=True, exist_ok=True)
    if not folder.is_dir():
        raise ValueError("output folder is not a directory: %r" % (str(folder),))
    return folder


def verify_missed(line):
    """Check the line against every measured fact about it.

    Each check raises its own ValueError naming exactly what went
    wrong, so a bad line fails loudly instead of writing quietly.
    """
    if not isinstance(line, str):
        raise ValueError("line must be a str, got %s" % type(line).__name__)
    if line == "":
        raise ValueError("line must not be empty")
    if line.strip() == "":
        raise ValueError("line must not be only whitespace")
    if len(line) != 55:
        raise ValueError("line must be 55 characters, got %d" % len(line))
    if len(line.encode("utf-8")) != 55:
        raise ValueError("line must be 55 bytes, got %d" % len(line.encode("utf-8")))
    if line.strip() != line:
        raise ValueError("line must not have leading or trailing whitespace")
    if "\n" in line:
        raise ValueError("line must be a single line, found a newline")
    if "\r" in line:
        raise ValueError("line must not contain a carriage return")
    if "\t" in line:
        raise ValueError("line must not contain a tab")
    if "  " in line:
        raise ValueError("line must not contain a double space")
    if line[0] != "M":
        raise ValueError("line must start with 'M', got %r" % line[0])
    if line[-1] != ".":
        raise ValueError("line must end with a period, got %r" % line[-1])
    if line.count(".") != 1:
        raise ValueError("line must contain exactly 1 period, got %d" % line.count("."))
    if line.count(",") != 1:
        raise ValueError("line must contain exactly 1 comma, got %d" % line.count(","))
    if line.count(" ") != 10:
        raise ValueError("line must contain exactly 10 spaces, got %d" % line.count(" "))
    if "!" in line:
        raise ValueError("line must not contain an exclamation mark")
    if "?" in line:
        raise ValueError("line must not contain a question mark")
    if ";" in line:
        raise ValueError("line must not contain a semicolon")
    if ":" in line:
        raise ValueError("line must not contain a colon")
    if '"' in line:
        raise ValueError("line must not contain a double quote")
    if "'" in line:
        raise ValueError("line must not contain an apostrophe")
    if any(ch.isdigit() for ch in line):
        raise ValueError("line must not contain a digit")
    parts = line.split(".")
    if len(parts) != 2:
        raise ValueError("line split on '.' must give 2 parts, got %d" % len(parts))
    if len(parts[0]) != 54:
        raise ValueError("line before the period must be 54 characters, got %d" % len(parts[0]))
    if parts[1] != "":
        raise ValueError("line after the period must be empty, got %r" % parts[1])
    if sum(1 for ch in line if ch.isupper()) != 1:
        raise ValueError("line must contain exactly 1 capital, got %d" % sum(1 for ch in line if ch.isupper()))
    if sum(1 for ch in line if ch.islower()) != 42:
        raise ValueError("line must contain exactly 42 lowercase letters, got %d" % sum(1 for ch in line if ch.islower()))
    if sum(1 for ch in line if ch in _VOWELS) != 19:
        raise ValueError("line must contain exactly 19 vowels, got %d" % sum(1 for ch in line if ch in _VOWELS))
    if sum(1 for ch in line if ch.isalpha() and ch not in _VOWELS) != 24:
        raise ValueError("line must contain exactly 24 consonants, got %d" % sum(1 for ch in line if ch.isalpha() and ch not in _VOWELS))
    if sum(1 for ch in line if ch.isalpha()) != 43:
        raise ValueError("line must contain exactly 43 letters, got %d" % sum(1 for ch in line if ch.isalpha()))
    if line.count("deadline") != 2:
        raise ValueError("line must contain 'deadline' twice, got %d" % line.count("deadline"))
    if line.startswith("My deadline") is not True:
        raise ValueError("line must start with 'My deadline'")
    if line.endswith(", and it missed that one too.") is not True:
        raise ValueError("line must end with ', and it missed that one too.'")
    if line.index("missed") != 35:
        raise ValueError("'missed' must start at offset 35, got %d" % line.index("missed"))
    if line.index("too.") != 51:
        raise ValueError("'too.' must start at offset 51, got %d" % line.index("too."))
    if line.index("deadline") != 3:
        raise ValueError("first 'deadline' must start at offset 3, got %d" % line.index("deadline"))
    if line.index("deadline", 4) != 18:
        raise ValueError("second 'deadline' must start at offset 18, got %d" % line.index("deadline", 4))
    if line[11:18] != " had a ":
        raise ValueError("gap between the two deadlines must be ' had a ', got %r" % line[11:18])
    if line[27:35] != " and it ":
        raise ValueError("hinge between the setup and the punch must be ' and it ', got %r" % line[27:35])
    if line[26] != ",":
        raise ValueError("character 26 must be the comma, got %r" % line[26])
    if line[27] != " ":
        raise ValueError("character 27 must be the space after the comma, got %r" % line[27])
    if line[:27] != "My deadline had a deadline,":
        raise ValueError("setup must be 'My deadline had a deadline,', got %r" % line[:27])
    if len(line[:27]) != 27:
        raise ValueError("setup must be 27 characters, got %d" % len(line[:27]))
    if line[:27].endswith(",") is not True:
        raise ValueError("setup must end with the comma")
    if line[28:] != "and it missed that one too.":
        raise ValueError("punch must be 'and it missed that one too.', got %r" % line[28:])
    if len(line[28:]) != 27:
        raise ValueError("punch must be 27 characters, got %d" % len(line[28:]))
    if line[28:].startswith("and") is not True:
        raise ValueError("punch must start with 'and'")
    if line.index("and") != 28:
        raise ValueError("'and' must start at offset 28, got %d" % line.index("and"))
    if line.index("it", 30) != 32:
        raise ValueError("'it' must start at offset 32, got %d" % line.index("it", 30))
    if line.index("that") != 42:
        raise ValueError("'that' must start at offset 42, got %d" % line.index("that"))
    if line.index("one") != 47:
        raise ValueError("'one' must start at offset 47, got %d" % line.index("one"))
    if line.index("deadline", 4) - line.index("deadline") != 15:
        raise ValueError("the two deadlines must sit 15 offsets apart, got %d" % (line.index("deadline", 4) - line.index("deadline")))
    if len(set(ch.lower() for ch in line if ch.isalpha())) != 12:
        raise ValueError("line must use exactly 12 distinct letters, got %d" % len(set(ch.lower() for ch in line if ch.isalpha())))
    if len(set(w.strip(".,") for w in line.split())) != 10:
        raise ValueError("line must hold exactly 10 distinct words, got %d" % len(set(w.strip(".,") for w in line.split())))
    if tuple(len(w) for w in line.split()) != _SHAPE:
        raise ValueError("word lengths must be %r, got %r" % (_SHAPE, tuple(len(w) for w in line.split())))
    for offset, char in _SPOTS:
        if line[offset] != char:
            raise ValueError("character at offset %d must be %r, got %r" % (offset, char, line[offset]))
    words = line.split()
    if len(words) != 11:
        raise ValueError("line must contain exactly 11 words, got %d" % len(words))
    stripped = [w.strip(".,") for w in words]
    if stripped.count("deadline") != 2:
        raise ValueError("line must contain the word 'deadline' twice, got %d" % stripped.count("deadline"))
    if words.count("deadline") != 1:
        raise ValueError("bare 'deadline' must appear once (the other carries a comma), got %d" % words.count("deadline"))
    if words.count("deadline,") != 1:
        raise ValueError("'deadline,' must appear exactly once, got %d" % words.count("deadline,"))
    if words[0] != "My":
        raise ValueError("first word must be 'My', got %r" % words[0])
    if words[1] != "deadline":
        raise ValueError("second word must be 'deadline', got %r" % words[1])
    if words[4] != "deadline,":
        raise ValueError("fifth word must be 'deadline,', got %r" % words[4])
    if words[-1] != "too.":
        raise ValueError("last word must be 'too.', got %r" % words[-1])
    if words[7] != "missed":
        raise ValueError("eighth word must be 'missed', got %r" % words[7])
    for index, expected in enumerate(_WORDS):
        word, length, start, end, vowels, consonants, first, last = expected
        if words[index] != word:
            raise ValueError("word %d must be %r, got %r" % (index, word, words[index]))
        if len(words[index]) != length:
            raise ValueError("word %d %r must be %d characters, got %d" % (index, word, length, len(words[index])))
        if line.index(word, sum(len(w) + 1 for w in words[:index]) if index else 0) != start:
            raise ValueError("word %d %r must start at offset %d" % (index, word, start))
        if start + len(word) != end:
            raise ValueError("word %d %r must end at offset %d, got %d" % (index, word, end, start + len(word)))
        if sum(1 for ch in words[index] if ch in _VOWELS) != vowels:
            raise ValueError("word %d %r must hold %d vowels, got %d" % (index, word, vowels, sum(1 for ch in words[index] if ch in _VOWELS)))
        if sum(1 for ch in words[index] if ch.isalpha() and ch not in _VOWELS) != consonants:
            raise ValueError("word %d %r must hold %d consonants, got %d" % (index, word, consonants, sum(1 for ch in words[index] if ch.isalpha() and ch not in _VOWELS)))
        if words[index][0] != first:
            raise ValueError("word %d %r must start with %r, got %r" % (index, word, first, words[index][0]))
        if words[index].strip(".,")[-1] != last:
            raise ValueError("word %d %r must end with %r, got %r" % (index, word, last, words[index].strip(".,")[-1]))
        if words[index].strip(".,").isalpha() is not True:
            raise ValueError("word %d %r must be alphabetic once punctuation is stripped" % (index, word))
    for letter, count in _LETTERS:
        found = sum(1 for ch in line if ch.lower() == letter)
        if found != count:
            raise ValueError("letter %r must appear %d times, got %d" % (letter, count, found))
    lowered = line.lower()
    for banned in _FORBIDDEN:
        if banned.lower() in lowered:
            raise ValueError("line must never name itself: found %r" % banned)
    if "dog" in lowered:
        raise ValueError("line must not retread the dog-ate-it excuse")
    if "calendar" in lowered:
        raise ValueError("line must not blame the calendar")
    if "future self" in lowered:
        raise ValueError("line must not outsource to a future self")
    if "social construct" in lowered:
        raise ValueError("line must not philosophise about deadlines")
    return line


def miss_deadline(target, line):
    """Write the line directly to the target path, no temp file.

    The target is opened in binary mode, the encoded payload is
    written, the handle is closed inside the try block, and the
    flush runs inside the finally block wrapped in try/except:
    a flush after a close raises ValueError, and the close already
    flushed everything, so the wrapped flush is a safety net, not
    a second write. Nothing here creates a temporary file, moves
    one, or replaces one, which is the whole point of this rebuild.
    """
    payload = line.encode("utf-8")
    if len(payload) != 55:
        raise ValueError("payload must be 55 bytes, got %d" % len(payload))
    digest = hashlib.sha256(payload).hexdigest()
    handle = target.open("wb")
    try:
        written = handle.write(payload)
        if written != len(payload):
            raise ValueError("write must store 55 bytes, stored %d" % written)
        handle.close()
    finally:
        try:
            handle.flush()
        except ValueError:
            # The handle is already closed, and close() flushed
            # everything it held. Flushing a closed handle raises
            # ValueError, so this is expected, not an error.
            pass
    print("missed:", target, "|", len(payload), "bytes | sha256", digest)
    return digest


def recheck_missed(target, line, digest):
    """Read the file back and prove it holds exactly the line.

    Compares the bytes, the decoded text, the size on disk and the
    hash, and then seals the folder: the output folder must hold
    exactly one file, entry.txt, because a stray temporary file in
    the output folder is what killed the first entry for this
    bounty at the server's dev grade.
    """
    if not target.is_file():
        raise ValueError("entry file is missing after the write: %r" % (str(target),))
    raw = target.read_bytes()
    if len(raw) != 55:
        raise ValueError("entry file must be 55 bytes, got %d" % len(raw))
    if raw != line.encode("utf-8"):
        raise ValueError("entry file bytes differ from the line")
    text = target.read_text(encoding="utf-8", errors="strict")
    if text != line:
        raise ValueError("entry file text differs from the line")
    if text.strip() != text:
        raise ValueError("entry file text must not have stray whitespace")
    if len(text) != 55:
        raise ValueError("entry file text must be 55 characters, got %d" % len(text))
    if text.count(".") != 1:
        raise ValueError("entry file text must hold exactly 1 period, got %d" % text.count("."))
    if text.split() != line.split():
        raise ValueError("entry file words differ from the line")
    if hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError("entry file hash differs from the written hash")
    if target.stat().st_size != 55:
        raise ValueError("entry file size on disk must be 55, got %d" % target.stat().st_size)
    folder = target.parent
    entries = sorted(p.name for p in folder.iterdir())
    if entries != ["entry.txt"]:
        raise ValueError("output folder must hold only entry.txt, got %r" % (entries,))
    if target.name != "entry.txt":
        raise ValueError("entry file must be named entry.txt, got %r" % target.name)
    return digest


def split_setup_punch(line):
    """Split the line at the comma into its setup and its punch.

    The setup is the first 27 characters, "My deadline had a
    deadline,", and it ends with the comma. The punch is the last
    27 characters, "and it missed that one too.", and it starts
    with "and". One space joins them, so 27 + 1 + 27 = 55. The
    split is the joke's shape: everything before the comma builds
    the impossible object, everything after it drops it.
    """
    setup = line[:27]
    punch = line[28:]
    if setup != "My deadline had a deadline,":
        raise ValueError("setup must be 'My deadline had a deadline,', got %r" % setup)
    if punch != "and it missed that one too.":
        raise ValueError("punch must be 'and it missed that one too.', got %r" % punch)
    if line[27] != " ":
        raise ValueError("setup and punch must be joined by one space")
    return setup, punch


def describe_line(line):
    """Measure the line and return the numbers the guard checks.

    The description is the guard's mirror: the same counts,
    computed the same way, returned as a plain mapping so the
    report can show them and so a reader can see at a glance
    that the line is what the guard claims it is.
    """
    words = line.split()
    return {
        "chars": len(line),
        "bytes": len(line.encode("utf-8")),
        "words": len(words),
        "sentences": line.count("."),
        "spaces": line.count(" "),
        "commas": line.count(","),
        "capitals": sum(1 for ch in line if ch.isupper()),
        "lowercase": sum(1 for ch in line if ch.islower()),
        "vowels": sum(1 for ch in line if ch in _VOWELS),
        "consonants": sum(1 for ch in line if ch.isalpha() and ch not in _VOWELS),
        "letters": sum(1 for ch in line if ch.isalpha()),
        "distinct_letters": len(set(ch.lower() for ch in line if ch.isalpha())),
        "distinct_words": len(set(w.strip(".,") for w in words)),
        "deadline_mentions": line.count("deadline"),
        "setup_chars": len(line[:27]),
        "punch_chars": len(line[28:]),
    }


def serve_missed():
    """Verify, write, recheck, and report the one line."""
    folder = missed_dir()
    target = folder / "entry.txt"
    line = verify_missed(MISSED_LINE)
    setup, punch = split_setup_punch(line)
    facts = describe_line(line)
    if facts["chars"] != 55 or facts["words"] != 11 or facts["sentences"] != 1:
        raise ValueError("measured facts disagree with the guard: %r" % (facts,))
    digest = miss_deadline(target, line)
    recheck_missed(target, line, digest)
    print("missed: setup %r (%d chars) | punch %r (%d chars)" % (setup, len(setup), punch, len(punch)))
    print("missed: done |", target, "| 55 bytes | sha256", digest)
    return target


